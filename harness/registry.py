"""The game's block-state registry: which properties each block has and their defaults.

Loaded from harness/data/block_defaults.json (generated by tools/gen_block_defaults.py
from the pinned server jar).
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

from .blockstate import BlockState

_PATH = Path(__file__).resolve().parent / "data" / "block_defaults.json"


@lru_cache(maxsize=1)
def _load() -> dict:
    return json.loads(_PATH.read_text())


def complete(state: BlockState) -> BlockState:
    """Fill in every property the block has but the state omits, with its default.
    Raises for blocks or properties the registry does not know, so a new block
    kind is noticed instead of silently passed through."""
    blocks = _load()["blocks"]
    info = blocks.get(state.name)
    if info is None:
        if state.props:
            raise ValueError(f"{state.name} has no properties in the registry but state has {state.props}")
        if not _known_block(state.name):
            raise ValueError(f"unknown block {state.name}")
        return state
    given = dict(state.props)
    for key, value in given.items():
        if key not in info["values"]:
            raise ValueError(f"{state.name} has no property {key!r}")
        if value not in info["values"][key]:
            raise ValueError(f"{state.name}[{key}={value}] is not a valid value")
    full = dict(info["default"])
    full.update(given)
    return BlockState(state.name, tuple(sorted(full.items())))


@lru_cache(maxsize=1)
def _propertyless_blocks() -> set[str]:
    return set(_load().get("propertyless", []))


def _known_block(name: str) -> bool:
    known = _propertyless_blocks()
    return not known or name in known
